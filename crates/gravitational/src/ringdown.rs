/// The dimensionless frequency `Mω` and quality factor `Q` of mode `(l, m, n)` of a Kerr black
/// hole with spin `j`, or `None` for a mode outside the fits.
pub fn qnm(l: u32, m: i32, n: u32, j: f64) -> Option<(f64, f64)> {
    let (_, f, q, _, _) = FITS.iter().find(|row| row.0 == (l, m, n))?;
    Some((f[0] + f[1] * (1.0 - j).powf(f[2]), q[0] + q[1] * (1.0 - j).powf(q[2])))
}

/// The ringing frequency (Hz) of a black hole of mass `mass` (kg, in the detector frame for an
/// observed signal) for the dimensionless frequency `f = Mω`: `fc³/(2πGM)`.
pub fn frequency(mass: f64, f: f64) -> f64 {
    f * C.powi(3) / (2.0 * PI * G * mass)
}

/// The damping time (s) of a mode ringing at `frequency` (Hz) with quality factor `q`: `Q/(πf)`.
pub fn damping_time(frequency: f64, q: f64) -> f64 {
    q / (PI * frequency)
}

