    /// The modes whose quality-factor fit misses the maximum error the paper states.
    const Q_WORSE: [(u32, i32, u32); 11] = [(2, -1, 1), (4, 0, 0), (4, 0, 1), (4, 0, 2), (4, 1, 0), (4, 1, 1), (4, 1, 2), (4, 2, 0), (4, 2, 1), (4, 2, 2), (4, 4, 2)];

    #[test]
    fn every_fit_against_the_tables() {
        let mut checked = 0;
        for line in TABLES.lines() {
            let mut words = line.split_whitespace();
            let (l, n, j): (u32, u32, f64) = (words.next().unwrap().parse().unwrap(), words.next().unwrap().parse().unwrap(), words.next().unwrap().parse().unwrap());
            for (k, pair) in words.enumerate() {
                let m = l as i32 - k as i32;
                let (wr, wi) = pair.split_once(',').unwrap();
                let (wr, wi): (f64, f64) = (wr.parse().unwrap(), wi.parse().unwrap());
                let (f, q) = qnm(l, m, n, j).unwrap();
                let (_, _, _, f_error, q_error) = FITS.iter().find(|row| row.0 == (l, m, n)).unwrap();
                // The tables round to four decimals, which allows 5×10⁻⁵ in each part.
                let (f_round, q_round) = (5e-5 / wr, 5e-5 / wr + 5e-5 / wi);
                assert!((f / wr - 1.0).abs() <= f_error / 100.0 + f_round, "F({l},{m},{n}) at j = {j}");
                let q_tol = if Q_WORSE.contains(&(l, m, n)) { 0.034 } else { q_error / 100.0 };
                assert!((q / (wr / (2.0 * wi)) - 1.0).abs() <= q_tol + q_round, "Q({l},{m},{n}) at j = {j}");
                checked += 1;
            }
        }
        assert_eq!(checked, 693);
        // The paper's maxima really are missed by those eleven: (4, 2, 0) at j = 0 is 2.9% off.
        let (_, q) = qnm(4, 2, 0, 0.0).unwrap();
        assert!((q / (0.8092 / (2.0 * 0.0941)) - 1.0).abs() > 0.028);
        assert!(qnm(5, 5, 0, 0.5).is_none());
    }

    #[test]
    fn gw150914() {
        // 68 M☉ and j = 0.67 (LVC, Tests of GR with GW150914, 2016): 248.4 Hz and 4.06 ms from
        // the central values, inside the predicted 251 ± 8 Hz and 4.0 ± 0.3 ms.
        let (f, q) = qnm(2, 2, 0, 0.67).unwrap();
        let hz = frequency(68.0 * SOLAR_MASS, f);
        assert!((hz / 248.4 - 1.0).abs() < 1e-3 && (damping_time(hz, q) / 4.06e-3 - 1.0).abs() < 2e-3, "{hz} {}", damping_time(hz, q));
        // At j = 0 the fit gives 0.3683 against Table II's 0.3737, inside its stated 1.85%.
        assert!((qnm(2, 2, 0, 0.0).unwrap().0 - 0.3683).abs() < 1e-4);
    }
